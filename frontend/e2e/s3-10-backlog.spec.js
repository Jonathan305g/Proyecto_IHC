import { test, expect } from '@playwright/test'
import { setupReview, loginReview } from './support/sprint3-fixtures.js'
async function fillStory(page, title = 'Mejorar confirmación') {
 await page.getByLabel('Título', { exact: true }).fill(title)
 await page.getByLabel('Descripción', { exact: true }).fill('Facilitar reconocer que los cambios se guardaron.')
 await page.getByLabel('Criterio de aceptación', { exact: true }).fill('La confirmación permanece visible al guardar.')
}
test('S3-10: crea, edita y conserva filtros de estado/prioridad al recargar', async ({ page }) => {
 const state = await setupReview(page, { empty: true }); await loginReview(page, '/backlog?plan_id=1')
 await page.getByRole('button', { name: 'Nueva historia', exact: true }).click()
 await page.getByRole('button', { name: 'Guardar historia', exact: true }).click()
 await expect(page.locator('#story-error-titulo')).toBeVisible()
 expect(state.stories).toHaveLength(0)
 await fillStory(page); await page.getByRole('button', { name: 'Guardar historia', exact: true }).click()
 await expect(page.getByTestId('historia-1')).toBeVisible()
 await page.reload(); await expect(page.getByTestId('historia-1')).toContainText('Mejorar confirmación')
 await page.getByRole('button', { name: 'Editar historia #1', exact: true }).click()
 await page.getByLabel('Prioridad', { exact: true }).selectOption('1')
 await page.getByLabel('Puntos', { exact: true }).fill('8')
 await page.getByLabel('Estado', { exact: true }).selectOption('en_progreso')
 await page.getByRole('button', { name: 'Guardar historia', exact: true }).click()
 await expect(page.getByTestId('historia-1')).toContainText('En progreso')
 await page.getByLabel('Filtrar por estado', { exact: true }).selectOption('en_progreso')
 await page.getByLabel('Filtrar por prioridad', { exact: true }).selectOption('1')
 await page.reload()
 await expect(page.getByLabel('Filtrar por estado', { exact: true })).toHaveValue('en_progreso')
 await expect(page.getByLabel('Filtrar por prioridad', { exact: true })).toHaveValue('1')
 await expect(page.getByTestId('historia-1')).toContainText('8')
 await expect(page.getByRole('button', { name: 'Subir historia #1', exact: true })).toBeDisabled()
 expect(state.stories[0].prioridad).toBe(1)
})

test('S3-10: reintentar creación manual tras perder confirmación conserva UUID y no duplica', async ({ page }) => {
 const state = await setupReview(page, { empty: true, manualResponseLost: true }); await loginReview(page, '/backlog?plan_id=1')
 await page.getByRole('button', { name: 'Nueva historia', exact: true }).click(); await fillStory(page)
 await page.getByRole('button', { name: 'Guardar historia', exact: true }).click()
 await expect(page.getByText('Confirmación de guardado perdida', { exact: false })).toBeVisible()
 await expect(page.getByLabel('Título', { exact: true })).toHaveValue('Mejorar confirmación')
 await page.getByRole('button', { name: 'Guardar historia', exact: true }).click()
 await expect(page.getByTestId('historia-1')).toBeVisible()
 expect(state.stories).toHaveLength(1)
 const sends = state.calls.filter(c => c.path.endsWith('/historias') && c.method === 'POST')
 expect(sends).toHaveLength(2); expect(sends[0].body.solicitud_id).toBe(sends[1].body.solicitud_id)
})
test('S3-10: conflicto de orden y fallo de consulta no se ocultan como lista vacía', async ({ page }) => {
 const state = await setupReview(page, { seedStories: true, orderConflict: true }); await loginReview(page, '/backlog?plan_id=1')
 await page.getByRole('button', { name: 'Bajar historia #1', exact: true }).click()
 await expect(page.getByText('El orden cambió.', { exact: false })).toBeVisible()
 await expect(page.locator('tbody tr').first()).toHaveAttribute('data-testid', 'historia-1')
 await page.getByRole('button', { name: 'Actualizar backlog', exact: true }).click()
 await page.getByRole('button', { name: 'Bajar historia #1', exact: true }).click()
 await expect(page.getByText('Orden guardado.', { exact: false })).toBeVisible()
 state.failList = true; await page.getByRole('button', { name: 'Actualizar backlog', exact: true }).click()
 await expect(page.getByText('No se pudo consultar el backlog', { exact: true })).toBeVisible()
 await expect(page.getByText('El backlog está vacío.', { exact: false })).toHaveCount(0)
 state.failList = false; await page.getByRole('button', { name: 'Reintentar', exact: true }).click()
 await expect(page.getByTestId('historia-1')).toBeVisible()
})

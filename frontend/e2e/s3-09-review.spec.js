test('S3-09: una confirmación perdida se consulta sin duplicar aprobación', async ({ page }) => {
 const state = await setupReview(page, { approvalResponseLost: true }); await loginReview(page)
 await page.getByLabel('Criterio de aceptación', { exact: true }).fill('La confirmación se ve al guardar.')
 await page.getByRole('button', { name: 'Aprobar y añadir al backlog' }).click()
 await page.getByRole('button', { name: 'Sí, aprobar y crear historia', exact: true }).click()
 await expect(page.getByText('No se confirmó la acción.', { exact: false })).toBeVisible()
 await page.getByRole('button', { name: 'Actualizar hallazgos', exact: true }).click()
 await expect(page.getByRole('link', { name: 'Ver historia #1', exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: 'Aprobar y añadir al backlog' })).toHaveCount(0)
 expect(state.stories).toHaveLength(1); expect(state.approvals).toBe(1)
})
test('S3-09: preparación y revisión de privacidad preceden al envío real', async ({ page }) => {
 const state = await setupReview(page, { empty: true }); await loginReview(page, '/revision?plan_id=1')
 await page.getByRole('checkbox', { name: /Resultado #1/ }).check()
 await page.getByRole('button', { name: 'Preparar análisis', exact: true }).click()
 await expect(page.getByRole('button', { name: 'Ejecutar análisis', exact: true })).toBeDisabled()
 await page.getByLabel('Texto revisado #1', { exact: true }).fill('No se reconoció la confirmación de guardado.')
 await page.getByRole('checkbox', { name: 'Confirmo que revisé la privacidad de todos estos textos.' }).check()
 await page.getByRole('button', { name: 'Guardar revisión de privacidad', exact: true }).click()
 await expect(page.getByRole('button', { name: 'Ejecutar análisis', exact: true })).toBeEnabled()
 await page.getByLabel('Texto revisado #1', { exact: true }).fill('Segunda revisión del texto.')
 await expect(page.getByRole('button', { name: 'Ejecutar análisis', exact: true })).toBeDisabled()
 await page.getByRole('checkbox', { name: 'Confirmo que revisé la privacidad de todos estos textos.' }).check()
 await page.getByRole('button', { name: 'Guardar revisión de privacidad', exact: true }).click()
 await page.getByRole('button', { name: 'Ejecutar análisis', exact: true }).click()
 await page.getByRole('button', { name: 'Importar borradores válidos', exact: true }).click()
 await expect(page.getByLabel('Resumen revisado', { exact: true })).toBeVisible()
 expect(state.approvals).toBe(0)
 expect(state.calls.filter(c => c.path.endsWith('/ejecutar'))).toHaveLength(1)
})

import { test, expect } from '@playwright/test'
import { setupReview, loginReview } from './support/sprint3-fixtures.js'

test('S3-09: contrasta origen, guarda borrador, recarga y aprueba una historia', async ({ page }) => {
 const state = await setupReview(page); await loginReview(page)
 await expect(page.getByRole('heading', { name: 'Observaciones originales', exact: true })).toBeVisible()
 await expect(page.getByText('Propuesta inicial de IA', { exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: 'Aprobar y añadir al backlog' })).toBeDisabled()
 await page.getByLabel('Resumen revisado', { exact: true }).fill('Resumen revisado por el equipo')
 await page.getByLabel('Criterio de aceptación', { exact: true }).fill('La confirmación permanece visible después de guardar.')
 await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
 await expect(page.getByText('Borrador guardado. Todavía no está aprobado.')).toBeVisible()
 expect(state.stories).toHaveLength(0)
 await page.reload(); await expect(page.getByLabel('Resumen revisado', { exact: true })).toHaveValue('Resumen revisado por el equipo')
 await page.getByRole('button', { name: 'Aprobar y añadir al backlog' }).click()
 await page.getByRole('button', { name: 'Sí, aprobar y crear historia', exact: true }).click()
 await expect(page.getByRole('link', { name: 'Ver historia #1', exact: true }).first()).toBeVisible()
 expect(state.stories).toHaveLength(1); expect(state.approvals).toBe(1)
 await page.getByRole('link', { name: 'Ver historia #1', exact: true }).first().click()
 await expect(page.getByRole('heading', { name: 'Hallazgo de origen #1' })).toBeVisible()
 await page.reload(); await expect(page.getByText('La confirmación pasó desapercibida.', { exact: true })).toBeVisible()
})
